const { buildSync } = require('esbuild')
const { resolve } = require('node:path')
const { readFileSync } = require('node:fs')
const Module = require('node:module')
const assert = require('node:assert/strict')
const React = require('react')
const { renderToString } = require('react-dom/server')

const result = buildSync({ entryPoints: [resolve('src/previews/LoginPreviews.jsx')], bundle: true, write: false, metafile: true, platform: 'node', format: 'cjs', packages: 'external', loader: { '.css': 'empty' } })
assert.ok(Object.keys(result.metafile.inputs).every(path => (path.replaceAll('\\', '/').startsWith('src/previews/') || path.replaceAll('\\', '/') === 'src/components/design/Identity.jsx')))
const mod = new Module(resolve('previews.generated.cjs'), module)
mod.filename = resolve('previews.generated.cjs'); mod.paths = module.paths; mod._compile(result.outputFiles[0].text, mod.filename)
for (const variant of ['a', 'b', 'c']) {
  const html = renderToString(React.createElement(mod.exports.default, { variant }))
  assert.ok(html.includes(`design-${variant}`))
  for (const copy of ['SmartSpend', 'Welcome back', 'Username', 'Password', 'Sign in', 'Create an account', 'No credentials are submitted']) assert.ok(html.includes(copy))
  assert.equal((html.match(/readonly=""/gi) || []).length, 2)
  assert.ok(!html.includes('<form') && !html.includes('type="submit"') && !html.includes(' name='))
  assert.ok(html.includes('aria-label="Show password"') && html.includes('aria-current="page"'))
  const source = readFileSync(resolve(`design-preview/${variant}/index.html`), 'utf8')
  assert.ok(source.includes(`data-design="${variant}"`))
  assert.ok(source.includes('/src/previews/main.jsx') && !source.includes('/src/main.jsx'))
  console.log(`PASS preview ${variant.toUpperCase()}: standalone entry, consistent content, read-only non-submitting fields`)
}
buildSync({ entryPoints: [resolve('src/previews/previews.css')], write: false, minify: true })
console.log('PASS preview CSS compiles (not a visual/viewport test)')
const css = readFileSync(resolve('src/previews/previews.css'), 'utf8')
assert.ok(css.includes('html { font-size: 16px;'))
assert.ok(css.includes('min-height: 100dvh;'))
assert.ok(css.includes('minmax(480px, 560px)'))
assert.ok(css.includes('clamp(56px, 5vw, 80px)'))
assert.ok(css.includes('font-size: 18px; min-height: 58px;'))
assert.ok(!/zoom\s*:|scale\s*\(/.test(css))
assert.ok(!/min\((?:1020|1040|680|430)px/.test(css))
assert.ok(css.includes('.gold-grid'))
console.log('PASS full-screen sizing and readable typography source guards (not computed browser styles)')
const source = readFileSync(resolve('src/previews/LoginPreviews.jsx'), 'utf8')
assert.ok(!/\bfetch\s*\(|XMLHttpRequest|localStorage|sessionStorage|from ['"].*api/.test(source))
assert.ok(!readFileSync(resolve('src/main.jsx'), 'utf8').includes('previews'))
console.log('PASS working app entry unchanged; preview dependency graph has no app/API imports')
